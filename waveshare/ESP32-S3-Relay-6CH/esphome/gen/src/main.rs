//! Regenerate `src/proto/api.rs` (prost types) and `src/proto/ids.rs` (message id table)
//! from `proto/api.proto`. Run from the esphome/ directory: `cargo run --manifest-path gen/Cargo.toml`.
//! Output is committed so normal builds need no protoc.

use heck::ToUpperCamelCase;
use std::fs;
use std::path::PathBuf;

fn main() {
    let protoc = protoc_bin_vendored::protoc_bin_path().expect("vendored protoc");
    std::env::set_var("PROTOC", protoc);
    let out = PathBuf::from("src/proto");
    let mut cfg = prost_build::Config::new();
    cfg.out_dir(&out);
    cfg.default_package_filename("api");
    cfg.compile_protos(&["proto/api.proto"], &["proto"]).expect("compile api.proto");
    println!("wrote {}", out.join("api.rs").display());

    // prost drops custom options, so scrape `option (id) = N;` per message from the source.
    let src = fs::read_to_string("proto/api.proto").expect("read api.proto");
    let mut ids: Vec<(String, u32)> = Vec::new();
    let mut current: Option<String> = None;
    for line in src.lines() {
        let t = line.trim();
        if let Some(rest) = t.strip_prefix("message ") {
            current = rest.split(|c: char| !c.is_alphanumeric() && c != '_').next().map(str::to_string);
        } else if t.starts_with('}') {
            current = None;
        } else if let (Some(name), Some(rest)) = (&current, t.strip_prefix("option (id) = ")) {
            let n: u32 = rest.trim_end_matches(';').trim().parse().expect("id number");
            // Match prost's Rust type naming (e.g. BluetoothLEAdvertisement -> BluetoothLeAdvertisement).
            ids.push((name.to_upper_camel_case(), n));
        }
    }
    ids.sort_by_key(|(_, id)| *id);
    let mut rs = String::from(
        "// Generated by `cargo run --manifest-path gen/Cargo.toml`; do not edit.\n\
         use super::api::*;\nuse crate::ApiMessage;\n\n",
    );
    for (name, id) in &ids {
        rs.push_str(&format!("impl ApiMessage for {name} {{ const ID: u32 = {id}; }}\n"));
    }
    rs.push_str("\n/// Human-readable message name for logging.\npub fn message_name(id: u32) -> &'static str {\n    match id {\n");
    for (name, id) in &ids {
        rs.push_str(&format!("        {id} => \"{name}\",\n"));
    }
    rs.push_str("        _ => \"Unknown\",\n    }\n}\n");
    fs::write(out.join("ids.rs"), rs).expect("write ids.rs");
    println!("wrote {} ({} message ids)", out.join("ids.rs").display(), ids.len());
}
